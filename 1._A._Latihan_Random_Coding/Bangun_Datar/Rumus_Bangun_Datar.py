print ("\n Persegi Panjang \n")


p = int (input ("Masukkan sisi p : "))
l = int (input ("Masukkan sisi l : "))


luas_persegi_panjang = p * l
keliling_persegi_panjang = 2 * (p + l)


print ("Luas Persegi Panjang = ", luas_persegi_panjang)
print ("Keliling Persegi Panjang = ", keliling_persegi_panjang)


print ("\n --- Batas --- \n")



print ("\n Lingkaran \n")


phi = 3.14
r = int (input ("Masukkan r : "))


luas_lingkaran = phi * r * r 
keliling_lingkaran = 2 * phi * r


print ("Luas lingkaran = ", luas_lingkaran)
print ("Keliling lingkaran = ", keliling_lingkaran)


print ("\n --- Batas --- \n")




print ("\n Segitiga \n")


